// Regenerates firmware/mechakin_comms/setup_qr.h.
// Run again if you change AP_SSID / AP_PASS in mechakin_comms.ino:
//   cd tools/qr-gen && npm install && AP_SSID=MechaKin-002 AP_PASS=secret123 npm start
import QRCode from 'qrcode';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ssid = process.env.AP_SSID ?? 'MechaKin-001';
const pass = process.env.AP_PASS ?? 'mechakin123';
const esc = (s) => s.replace(/([\;,:"])/g, '\\$1'); // Wi-Fi QR escaping
const codes = {
  QR_WIFI: `WIFI:T:WPA;S:${esc(ssid)};P:${esc(pass)};;`, // phone camera: "join network"
  QR_URL: 'http://192.168.4.1/', // phone camera: open the setup page
};

let out = `// GENERATED by tools/qr-gen/make-qr.mjs. Do not edit by hand.
// Wi-Fi hotspot: ${ssid}
#pragma once
#include <stdint.h>
// Each QR: size (modules per side), then rows packed MSB-first, ceil(size/8) bytes per row.
`;
for (const [name, text] of Object.entries(codes)) {
  const qr = QRCode.create(text, { errorCorrectionLevel: 'M' });
  const n = qr.modules.size;
  const rowBytes = Math.ceil(n / 8);
  const bytes = [];
  for (let y = 0; y < n; y++) {
    for (let b = 0; b < rowBytes; b++) {
      let v = 0;
      for (let bit = 0; bit < 8; bit++) {
        const x = b * 8 + bit;
        if (x < n && qr.modules.get(y, x)) v |= 0x80 >> bit;
      }
      bytes.push(v);
    }
  }
  out += `\n// "${text}" (version ${qr.version}, ${n}x${n})\nconst uint8_t ${name}_SIZE = ${n};\nconst uint8_t ${name}[] = {\n`;
  for (let i = 0; i < bytes.length; i += 16) {
    out += '  ' + bytes.slice(i, i + 16).map((v) => '0x' + v.toString(16).padStart(2, '0')).join(', ') + ',\n';
  }
  out += '};\n';
  console.log(`${name}: "${text}" -> ${n}x${n}`);
}
const target = join(dirname(fileURLToPath(import.meta.url)), '../../firmware/mechakin_comms/setup_qr.h');
writeFileSync(target, out);
console.log(`wrote ${target}`);
